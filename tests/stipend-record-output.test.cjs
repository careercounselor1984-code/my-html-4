'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const s=fs.readFileSync('index.html','utf8');
const m=s.match(/"id":"p06","title":"[^"]+","b64":"([A-Za-z0-9+/=]+)"/);
assert(m,'p06 module exists');
const page=Buffer.from(m[1],'base64').toString('utf8');
const def=page.match(/^        function buildPaymentRecordSection\([\s\S]*?^        }\n/m);
assert(def,'conditional summary helper found');
const summary=vm.runInNewContext('('+def[0].trim()+')');
const base={reportedIncome:0,nonProgramIncome:0,programIncome:0,excludedIncome:0,criteria:1538543,decision:'소득 없음',pay:600000};
const simple=summary(base,'없음',100,null);
assert.equal(simple,'- 소득 발생: 없음\n- 최종 지급액: 600,000원','no income and no changes => concise output plus final amount');
assert(!/기본 수당|가족 수당|신고소득 합계|소득 판정 기준금액/.test(simple));
const change=summary({...base,pay:700000},'없음',100,{typeLabel:'대상자 추가',before:0,after:1,date:'2026.10.13',reason:'자녀 출생'});
assert.match(change,/가족수당 변동: 대상자 추가/);
assert.match(change,/0명 → 1명/);
assert.match(change,/변동 적용일: 2026.10.13/);
assert.match(change,/변동 사유: 자녀 출생/);
assert.match(change,/최종 지급액: 700,000원/);
const removal=summary({...base,pay:600000},'없음',100,{typeLabel:'대상자 제외',before:1,after:0,date:'2026.10.13',reason:'연령 초과'});
assert.match(removal,/대상자 제외/);
assert.match(removal,/1명 → 0명/);
assert.equal((removal.match(/최종 지급액:/g)||[]).length,1,'final amount appears only once');
const programOnly=summary({...base,reportedIncome:92800,programIncome:92800,decision:'전액 지급 가능'},'있음',100,null);
assert.equal(programOnly,'- 취업지원프로그램 수당: 92,800원\n- 최종 지급액: 600,000원');
const income=summary({...base,reportedIncome:450000,nonProgramIncome:400000,programIncome:50000,decision:'전액 지급 가능'},'있음',100,null);
assert.equal(income,'- 근로·사업 등 신고소득: 400,000원\n- 취업지원프로그램 수당: 50,000원\n- 최종 지급액: 600,000원');
assert(!/소득 판정 기준금액|신고소득 합계|소득 판정:/.test(income));
const excluded=summary({...base,excludedIncome:120000},'있음',100,null);
assert.match(excluded,/산정 제외·참고 금액: 120,000원/);
const limited=summary({...base,pay:300000},'없음',50,null);
assert.match(limited,/일부 미이행/);
assert.match(limited,/최종 지급액: 300,000원/);
assert.doesNotMatch(page,/<소득 신고 상세 내역>/,'redundant income detail block removed');
assert.doesNotMatch(page,/incomeDetailSection/,'redundant income detail variable removed');
assert.match(page,/const hasIncome = document.querySelector/,'income calculation ignores hidden stale rows');
assert.match(page,/const paymentRecord = buildPaymentRecordSection/,'output uses conditional summary');
assert.match(page,/id="familyChangeFields" class="hidden\b/,'family controls hidden by default');
console.log('OK: stipend summary normal, income, family addition/removal, partial compliance; conditional detail display');
