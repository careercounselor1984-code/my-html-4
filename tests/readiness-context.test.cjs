'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const script=html.match(/<script id="clg-work24-counsel-bridge-v113-script">([\s\S]*?)<\/script>/)[1];
const ids=[...script.matchAll(/\$\('([^']+)'\)/g)].map(m=>m[1]);
const dom=new JSDOM([...new Set(ids)].map(id=>id==='frame'?'<iframe id="frame"></iframe>':`<div id="${id}"></div>`).join(''),{runScripts:'outside-only',url:'https://example.test/'});
const w=dom.window, d=w.document;
const frame=d.getElementById('frame'), child=frame.contentDocument;
const names=['q1_jobGoal','q2_jobWill','q3_jobPlan','q4_jobSkill','q5_jobInfo','q6_competencyChange','q7_barrier','health'];
child.body.innerHTML='<button id="readinessSendBtn">send</button><input id="clgIapRegNo"><input id="counselingDate">'+names.map((name,i)=>`<input type="radio" name="${name}" id="answer${i}">`).join('');
let current=frame, clicks=0;
w.clgGetActiveFrame=()=>current;
w.loadPage=()=>{};
child.getElementById('readinessSendBtn').addEventListener('click',()=>clicks++);
w.eval(script);
function bridge(type,payload){w.dispatchEvent(new w.MessageEvent('message',{source:w,data:{marker:'CLG_COUNSEL_BRIDGE_V113',type,payload}}));}
const text=id=>d.getElementById(id).textContent;
(async()=>{
 bridge('BRIDGE_READY');
 assert.equal(text('clgBridgeTitle'),'구직준비도 연결');
 assert.equal(text('clgBridgeQuickBtn'),'설문 전송');
 assert.match(text('clgBridgeWho'),/0\/8/);
 d.getElementById('clgBridgeQuickBtn').click();assert.equal(clicks,0);
 for(let i=0;i<8;i++)child.getElementById('answer'+i).checked=true;
 child.dispatchEvent(new w.Event('change'));
 assert.match(text('clgBridgeWho'),/8\/8/);
 bridge('PENDING_STATE',{basic:{name:'test',sentAt:'2026-10-18'}});
 assert.equal(text('clgBridgeTitle'),'구직준비도 연결');
 d.getElementById('clgBridgeApplyBtn').click();assert.equal(clicks,1);
 child.defaultView.dispatchEvent(new w.MessageEvent('message',{source:w,data:{marker:'CLG_READINESS_PAGE_V150',type:'READINESS_SAVED'}}));
 assert.match(text('clgBridgeMsg'),/저장 확인 완료/);
 child.getElementById('clgIapRegNo').value='changed';child.dispatchEvent(new w.Event('change'));
 assert.doesNotMatch(text('clgBridgeMsg'),/저장 확인 완료/);
 current={contentDocument:d};
 w.dispatchEvent(new w.Event('clg-tab-switch'));await new Promise(r=>setTimeout(r,100));
 assert.equal(text('clgBridgeTitle'),'Work24 기본정보 도착');
 current=frame;w.dispatchEvent(new w.Event('clg-tab-frame-load'));await new Promise(r=>setTimeout(r,100));
 assert.equal(text('clgBridgeTitle'),'구직준비도 연결');
 console.log('Readiness active-tab recognition, incomplete-answer guard, transfer and status checks passed');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>w.close());
