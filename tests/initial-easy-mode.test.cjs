'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const javascript=fs.readFileSync(path.join(root,'initial-easy-mode.js'),'utf8');
const style=fs.readFileSync(path.join(root,'initial-easy-mode.css'),'utf8');
new vm.Script(javascript,{filename:'initial-easy-mode.js'});
assert.ok(style.includes('body.clg-initial-easy .panel .section'),'minimal screen hides advanced panels');
assert.ok(javascript.includes("document.body.classList.add('clg-initial-easy')"),'easy mode should be default');
assert.ok(javascript.includes("by('easyDetail').addEventListener('click'"),'details should stay available');
assert.ok(javascript.includes("if(wasEdited||(opinion&&(!lastGenerated||opinion!==clean(lastGenerated))))"),'manual opinion guard missing');
assert.ok(javascript.includes("if(old&&old!==prior[id])return false"),'manual field guard missing');
assert.ok(javascript.includes("for(const id of Object.keys(prior))"),'stale generated fields must clear');
assert.ok(javascript.includes("if(new TextEncoder().encode(record).length>4000)"),'4k copy guard');
assert.ok(javascript.includes("if(!by('easyVerified').checked)"),'required actual confirmation');
assert.ok(javascript.includes("if(clean(by('easyMemo').value)!==appliedMemo)"),'stale memo guard');
assert.ok(!javascript.includes(".slice(0,330)"),'notes should not be silently clipped');
for(const id of ['p01','p02']){
 const match=html.match(new RegExp('"id":"'+id+'","title":"[^"]+","b64":"([^"]+)"'));
 assert.ok(match,id+' embedded page missing');
 const page=Buffer.from(match[1],'base64').toString('utf8');
 assert.ok(page.includes('initial-easy-mode.js?v=20261014a'),id+' quick script missing');
 assert.ok(page.includes('initial-easy-mode.css?v=20261014a'),id+' quick css missing');
 assert.ok(page.includes('id="copyRecordBtn"'),id+' detailed copy removed');
 assert.ok(page.includes('id="initialSummaryPreview"'),id+' summary preview removed');
 if(id==='p01')assert.ok(page.includes('id="familyMemberList"'),'type I family controls removed');
 const scripts=[...page.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)];
 scripts.forEach((part,i)=>new vm.Script(part[1],{filename:id+' inline '+i}));
}
const script=javascript.slice(javascript.indexOf('const attr='),javascript.indexOf('function setExisting('));
const context=vm.createContext({});
const parse=vm.runInContext(script+'\nparse',context);
const a=parse('희망직무: 자동차 생산\n목표시기: 6개월 이내\n참여이유: 취업지원서비스 이용\n현재상태: 구직 준비 중\n어려움: 반복된 구직 실패로 자신감 저하\n지원요청: 알선, 이력서 보완');
assert.equal(a.fields.strategyTargetJob,'자동차 생산');
assert.equal(a.fields.strategyTiming,'6개월 이내');
assert.equal(a.fields.mainDifficulty,'반복된 구직 실패로 자신감 저하');
assert.equal(a.requested.length,1);
assert.equal(a.unknown.length,0);
const b=parse('사회복지사 취업 희망\n취업 목표 6개월 이내\n매우 특수한 면담 메모');
assert.ok(b.fields.strategyTargetJob.includes('사회복지사'));
assert.equal(b.fields.strategyTiming,'6개월 이내');
assert.deepEqual(Array.from(b.unknown),['매우 특수한 면담 메모']);
console.log('Initial easy entry: both types, parser, no-overwrite and 4k protections passed.');
