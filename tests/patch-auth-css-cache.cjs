'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
let html=fs.readFileSync('index.html','utf8');
const previous='<link rel="stylesheet" href="./journal-auth.css?v=20261011">';
const revised='<link rel="stylesheet" href="./journal-auth.css?v=20261011-pinfix2">';
assert.equal(html.split(previous).length-1,1,'one original auth CSS link');
assert.equal(html.split(revised).length-1,0,'cache-buster not already applied');
const originalBytes=html.length;
html=html.replace(previous,revised);
assert(html.includes('src="./vendor/supabase.min.js"'));
assert.equal(html.length-originalBytes,revised.length-previous.length);
fs.writeFileSync('index.html',html,'utf8');
console.log('PIN_CSS_CACHE_BUST',previous,'->',revised,'bytes',html.length);
